#!/usr/bin/env python3
"""Generate the data request classes and their SpotifyApi entry points from spec/openapi.yaml.

  ./codegen/generate.py          rewrite every generated file
  ./codegen/generate.py --check  exit non-zero if a generated file differs from what the spec produces

codegen/requests.yaml names the class for each spec operation. Everything else comes from the spec:
verb, path, parameters and their types, the argument checks, Javadoc, deprecation and how the response
is read. The few places this library deliberately differs from the spec are spelled out in that file.
"""
import pathlib
import re
import sys
import textwrap

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec/openapi.yaml"
DESCRIPTOR = ROOT / "codegen/requests.yaml"
SOURCES = ROOT / "src/main/java"
BASE = "se.michaelthelin.spotify"
DATA = BASE + ".requests.data"
MODELS = SOURCES / "se/michaelthelin/spotify/model_objects"
API = SOURCES / "se/michaelthelin/spotify/SpotifyApi.java"
DOCS = "https://developer.spotify.com"
REFERENCE = DOCS + "/documentation/web-api/reference/"
WIDTH = 120
HEADER = "// Generated by codegen/generate.py from spec/openapi.yaml; edit those instead."

# Spec schemas whose model class does not follow the naming convention in model_class().
MODELS_BY_SCHEMA = {
    "PrivateUserObject": "User",
    "PublicUserObject": "User",
    "QueueObject": "PlaybackQueue",
    "ArtistDiscographyAlbumObject": "AlbumSimplified",
    "PagingFeaturedPlaylistObject": "FeaturedPlaylists",
}

# Parameters whose Java type is not the one their schema type maps to.
TYPES_BY_NAME = {
    "market": ("CountryCode", BASE + ".enums.CountryCode"),
}

RESERVED = {"public", "default", "private", "class", "new"}


class Unsupported(Exception):
    pass


# --- spec --------------------------------------------------------------------------------------------

class Spec:
    def __init__(self):
        self.doc = yaml.safe_load(SPEC.read_text())
        self.operations = {}
        for path, item in self.doc["paths"].items():
            for verb, op in item.items():
                if isinstance(op, dict) and "operationId" in op:
                    self.operations[op["operationId"]] = (verb.upper(), path, op)

    def deref(self, node):
        while isinstance(node, dict) and "$ref" in node:
            section, name = node["$ref"].split("/")[-2:]
            node = self.doc["components"][section][name]
        return node


def ref_name(node):
    return node["$ref"].split("/")[-1] if isinstance(node, dict) and "$ref" in node else None


def model_class(schema_name):
    """SavedAlbumObject -> SavedAlbum, SimplifiedTrackObject -> TrackSimplified, AlbumObject -> Album."""
    name = MODELS_BY_SCHEMA.get(schema_name)
    if not name:
        name = re.sub(r"Object$", "", schema_name)
        m = re.match(r"Simplified(\w+)", name)
        if m:
            name = m.group(1) + "Simplified"
    if not list(MODELS.rglob(name + ".java")):
        raise Unsupported(f"schema {schema_name} maps to {name}, which is no model class")
    return name


def model_import(name):
    source = next(MODELS.rglob(name + ".java"))
    return ".".join(source.relative_to(SOURCES).with_suffix("").parts)


# --- responses ---------------------------------------------------------------------------------------

class Returns:
    """What execute() returns and how it reads the body.

    kind is one of: none (the raw body), object, array, paging, cursor (a cursor-based paging),
    plain (a JSON array of strings or booleans, read without model adapters).
    """

    def __init__(self, kind, model=None, key=None):
        self.kind, self.model, self.key = kind, model, key

    @classmethod
    def parse(cls, text, key=None):
        m = re.fullmatch(r"(Paging|PagingCursorbased)<(\w+)>", text)
        if m:
            return cls("paging" if m.group(1) == "Paging" else "cursor", m.group(2), key)
        if text in ("String[]", "Boolean[]"):
            return cls("plain", text, key)
        if text.endswith("[]"):
            return cls("array", text[:-2], key)
        if text == "String":
            return cls("none")
        return cls("object", text, key)

    @property
    def java(self):
        return {"none": "String", "object": self.model, "array": f"{self.model}[]", "plain": self.model,
                "paging": f"Paging<{self.model}>", "cursor": f"PagingCursorbased<{self.model}>"}[self.kind]

    def imports(self):
        found = set()
        if self.kind in ("object", "array", "paging", "cursor"):
            found.add(model_import(self.model))
        if self.kind == "paging":
            found.add(BASE + ".model_objects.specification.Paging")
        if self.kind == "cursor":
            found.add(BASE + ".model_objects.specification.PagingCursorbased")
        if self.kind != "none":
            found.add(BASE + ".internal.ModelObjectJson")
        return found

    def expression(self, body):
        if self.kind == "none":
            return body
        key = f'"{self.key}", ' if self.key else ""
        if self.kind == "plain":
            return f"ModelObjectJson.plain({body}, {key}{self.model}.class)"
        method = {"object": "object", "array": "array", "paging": "paging", "cursor": "pagingCursorbased"}[self.kind]
        return f"ModelObjectJson.{method}({body}, {key}{self.model}.class)"


def paging_item(spec, schema):
    for part in spec.deref(schema).get("allOf", []):
        items = part.get("properties", {}).get("items")
        if items:
            return model_class(ref_name(items["items"]))
    raise Unsupported(f"{ref_name(schema)} has no items")


def read_schema(spec, schema, key=None):
    name = ref_name(schema)
    resolved = spec.deref(schema)
    if name in MODELS_BY_SCHEMA:
        return Returns("object", MODELS_BY_SCHEMA[name], key)
    if name and name.startswith("CursorPaging"):
        return Returns("cursor", paging_item(spec, schema), key)
    if name and name.startswith("Paging"):
        return Returns("paging", paging_item(spec, schema), key)
    if not name and any(ref_name(part) == "PagingObject" for part in resolved.get("allOf", [])):
        return Returns("paging", paging_item(spec, resolved), key)
    if name:
        return Returns("object", model_class(name), key)
    if resolved.get("type") == "array":
        items = resolved["items"]
        if ref_name(items):
            return Returns("array", model_class(ref_name(items)), key)
        if items.get("type") in ("string", "boolean"):
            return Returns("plain", "String[]" if items["type"] == "string" else "Boolean[]", key)
    properties = resolved.get("properties", {})
    if set(properties) == {"snapshot_id"}:
        return Returns("object", "SnapshotResult", key)
    if key is None and resolved.get("type") == "object" and len(properties) == 1:
        inner_key, inner = next(iter(properties.items()))
        return read_schema(spec, inner, inner_key)
    raise Unsupported("response shape")


def returns(spec, op, entry):
    if "returns" in entry:
        return Returns.parse(entry["returns"], entry.get("key"))
    responses = op["responses"]
    success = next((responses[c] for c in ("200", "201", "202", "204") if c in responses), None)
    schema = spec.deref(success).get("content", {}).get("application/json", {}).get("schema")
    return Returns("none") if schema is None else read_schema(spec, schema)


def success_description(spec, op):
    responses = op["responses"]
    success = next((responses[c] for c in ("200", "201", "202", "204") if c in responses), {})
    return spec.deref(success).get("description", "")


# --- documentation -----------------------------------------------------------------------------------

def javadoc_text(markdown):
    """The spec's Markdown as Javadoc HTML that passes doclint."""
    text = " ".join((markdown or "").split())
    text = text.replace("&", "&amp;").replace("@", "{@literal @}")
    text = re.sub(r"<br\s*/?>", "<br>", text)
    text = re.sub(r"`([^`]+)`", r"{@code \1}", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<![\w{])_([^_]+)_(?!\w)", r"<i>\1</i>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)",
                  lambda m: f'<a href="{DOCS + m.group(2) if m.group(2).startswith("/") else m.group(2)}">{m.group(1)}</a>',
                  text)
    return text.strip()


def wrap(text, indent, first="", hang=""):
    prefix = " " * indent + " * "
    lines = textwrap.wrap(text, WIDTH - len(prefix), initial_indent=first, subsequent_indent=hang,
                          break_long_words=False, break_on_hyphens=False)
    return [prefix + line for line in lines] or [prefix.rstrip()]


def doc(indent, *blocks):
    pad = " " * indent
    out = [pad + "/**"]
    for i, block in enumerate(b for b in blocks if b):
        if i:
            out.append(pad + " *")
        out.extend(block)
    out.append(pad + " */")
    return out


def summary(op):
    return javadoc_text(op.get("description") or op.get("summary"))


# --- parameters --------------------------------------------------------------------------------------

class Parameter:
    def __init__(self, name, where, schema, required):
        self.name, self.where, self.schema, self.required = name, where, schema, required
        self.description = schema.get("description", "")
        self.method = name + "_" if name in RESERVED else name
        self.value = self.method  # the expression handed to the builder, when it differs from the argument
        self.java, self.imports, self.checks = self.typed()

    def typed(self):
        name, schema, description = self.method, self.schema, self.description  # name: the Java identifier
        imports = set()
        if self.name in TYPES_BY_NAME:
            java, imported = TYPES_BY_NAME[self.name]
            return java, {imported}, [f"assert ({name} != null);"]
        kind = schema.get("type")
        enum = schema.get("enum")
        if kind == "string" and enum and set(enum) <= {"artist", "user", "album", "track", "show", "episode"}:
            return "ModelObjectType", {BASE + ".enums.ModelObjectType"}, [f"assert ({name} != null);"]
        if kind == "integer":
            java = "Long" if "Unix timestamp" in description else "Integer"
            suffix = "L" if java == "Long" else ""
            low = max([schema.get("minimum", 0)] + [int(n) for n in re.findall(r"Minimum: (\d+)", description)])
            high = schema.get("maximum")
            checks = [f"assert ({name} != null);",
                      f"assert ({low}{suffix} <= {name} && {name} <= {high}{suffix});" if high is not None
                      else f"assert ({name} >= {low}{suffix});"]
            return java, imports, checks
        if kind == "number":
            low, high = schema.get("minimum"), schema.get("maximum")
            checks = [f"assert ({name} != null);"]
            if low is not None and high is not None:
                checks.append(f"assert ({low}f <= {name} && {name} <= {high}f);")
            return "Float", imports, checks
        if kind == "boolean":
            return "Boolean", imports, [f"assert ({name} != null);"]
        if kind == "string" or (kind == "array" and self.where == "query"):
            checks = ["Preconditions.assertNotEmpty(%s);" % name]
            imports.add(BASE + ".internal.Preconditions")
            if enum:
                checks.append(f'assert ({name}.matches("{"|".join(enum)}"));')
            most = re.search(r"Maximum: (\d+) (?:IDs?|id|URIs)|maximum of (\d+) (?:IDs|items)", description)
            if most:
                checks.append(f'assert ({name}.split(",").length <= {most.group(1) or most.group(2)});')
            return "String", imports, checks
        if kind == "array" and schema.get("items", {}).get("type") == "string":
            imports |= {"java.util.List", BASE + ".internal.Preconditions"}
            checks = ["Preconditions.assertNotEmpty(%s);" % name]
            most = re.search(r"maximum of (\d+)|Maximum: (\d+)", description)
            if most:
                checks.append(f"assert ({name}.size() <= {most.group(1) or most.group(2)});")
            return "List<String>", imports, checks
        if kind == "array" and schema.get("items", {}).get("type") == "object":
            fields = schema["items"].get("properties", {})
            most = re.search(r"maximum of (\d+)|Maximum: (\d+)", description)
            checks = ["Preconditions.assertNotEmpty(%s);" % name]
            if most:
                checks.append(f"assert ({name}.size() <= {most.group(1) or most.group(2)});")
            if len(fields) == 1 and next(iter(fields.values())).get("type") == "string":
                # an array of one-field objects, e.g. [{"uri": ...}], takes the field values and wraps them itself
                field = next(iter(fields))
                self.value = f'RequestValues.objects({name}, "{field}")'
                self.description += f" Pass the {field} values; each is sent as {{@code {{\"{field}\": value}}}}."
                return "List<String>", {"java.util.List", BASE + ".internal.Preconditions", BASE + ".internal.RequestValues"}, checks
            return "List<Map<String, Object>>", {"java.util.List", "java.util.Map", BASE + ".internal.Preconditions"}, checks
        if kind == "object":
            return "Map<String, Object>", {"java.util.Map"}, [f"assert ({name} != null);"]
        raise Unsupported(f"type {kind} of parameter {name}")

    @property
    def setter(self):
        return {"path": "setPathParameter", "query": "setQueryParameter", "body": "setBodyParameter"}[self.where]


def parameters(spec, op, entry):
    params = []
    for raw in op.get("parameters", []):
        p = spec.deref(raw)
        if p["in"] not in ("path", "query"):
            raise Unsupported(f"{p['in']} parameter {p['name']}")
        params.append(Parameter(p["name"], p["in"], p["schema"], p["in"] == "path" or p.get("required", False)))
    body = (op.get("requestBody") or {})
    content = spec.deref(body).get("content", {})
    if content and "application/json" not in content:
        raise Unsupported(f"{next(iter(content))} request body")
    if content:
        schema = spec.deref(content["application/json"]["schema"])
        taken = {p.name for p in params}
        for name, prop in schema.get("properties", {}).items():
            if name not in taken:  # a body field duplicating a query parameter is ignored by Spotify when both are sent
                params.append(Parameter(name, "body", spec.deref(prop), name in schema.get("required", [])))
    fixed = entry.get("fixed", {})
    params = [p for p in params if p.name not in fixed]
    if "params" in entry:
        by_name = {p.name: p for p in params}
        params = [by_name[name] for name in entry["params"]]
    return params


# --- request class -----------------------------------------------------------------------------------

class Request:
    def __init__(self, spec, package, cls, entry):
        self.spec, self.package, self.cls, self.entry = spec, package, cls, entry
        if entry["operation"] not in spec.operations:
            raise Unsupported(f"unknown operation {entry['operation']}")
        self.verb, self.path, self.op = spec.operations[entry["operation"]]
        self.deprecated = self.op.get("deprecated", False)
        self.returns = returns(spec, self.op, entry)
        self.params = parameters(spec, self.op, entry)
        self.fixed = entry.get("fixed", {})
        self.method = cls[0].lower() + re.sub(r"Request$", "", cls)[1:]

    @property
    def qualified(self):
        return f"{DATA}.{self.package.replace('/', '.')}.{self.cls}"

    @property
    def required(self):
        """The SpotifyApi method's arguments: the required parameters, unless the descriptor lists them."""
        if "args" in self.entry:
            by_name = {p.name: p for p in self.params}
            return [by_name[name] for name in self.entry["args"]]
        return [p for p in self.params if p.required]

    def builder_base(self):
        names = {p.name: p for p in self.params}
        if self.returns.kind == "paging" and "limit" in names and "offset" in names:
            return f"AbstractDataPagingRequest.Builder<{self.returns.model}, Builder>", DATA + ".AbstractDataPagingRequest", {"limit", "offset"}
        if self.returns.kind == "cursor" and "limit" in names and "after" in names:
            return (f"AbstractDataPagingCursorbasedRequest.Builder<{self.returns.model}, {names['after'].java}, Builder>",
                    DATA + ".AbstractDataPagingCursorbasedRequest", {"limit", "after"})
        return f"AbstractDataRequest.Builder<{self.returns.java}, Builder>", None, set()

    def setter(self, p, overrides):
        head = f"@param {p.method} "
        text = ("Required. " if p.required else "Optional. ") + javadoc_text(p.description)
        lines = doc(4, [f"     * The {p.name} {p.where} parameter setter."],
                    wrap(text, 4, head, " " * len(head)) + [f"     * @return A {{@link {self.cls}.Builder}}."])
        if p.name in overrides:
            lines.append("    @Override")
        lines.append(f"    public Builder {p.method}(final {p.java} {p.method}) {{")
        lines += ["      " + c for c in p.checks]
        lines.append(f'      return {p.setter}("{p.name}", {p.value});')
        lines.append("    }")
        return lines

    def render(self):
        call = {"GET": "getJson", "POST": "postJson", "PUT": "putJson", "DELETE": "deleteJson"}[self.verb]
        base, base_import, overrides = self.builder_base()
        # POST and PUT always send a JSON body, even an empty {}, which keeps Spotify from rejecting them for a missing length
        has_body = self.verb in ("POST", "PUT") or any(p.where == "body" for p in self.params)
        imports = {"org.apache.hc.core5.http.ParseException", BASE + ".exceptions.SpotifyWebApiException",
                   DATA + ".AbstractDataRequest"} | self.returns.imports()
        if base_import:
            imports.add(base_import)
        if has_body:
            imports.add("org.apache.hc.core5.http.ContentType")
        for p in self.params:
            imports |= p.imports

        deprecation = [" * @deprecated This endpoint has been deprecated by Spotify."] if self.deprecated else None
        annotation = ["@Deprecated"] if self.deprecated else []
        package = f"{DATA}.{self.package.replace('/', '.')}"

        out = [f"package {package};", ""]
        out += [f"import {i};" for i in sorted(i for i in imports if not i.startswith("java."))]
        out += [""] + [f"import {i};" for i in sorted({"java.io.IOException"} | {i for i in imports if i.startswith("java.")})]
        out += ["", HEADER]
        out += doc(0, wrap(summary(self.op), 0),
                   [f' * @see <a href="{REFERENCE}{self.entry["operation"]}">Spotify Web API reference</a>'],
                   deprecation)
        out += annotation
        out += [f"public class {self.cls} extends AbstractDataRequest<{self.returns.java}> {{", ""]
        out += [f"  private {self.cls}(final Builder builder) {{", "    super(builder);", "  }", ""]
        out += doc(2, ["   * Send the request."],
                   wrap(javadoc_text(success_description(self.spec, self.op)) or "The response.", 2, "@return ", "        ")
                   + ["   * @throws IOException            In case of networking issues.",
                      "   * @throws SpotifyWebApiException The Web API returned an error further specified in this exception's root cause.",
                      "   * @throws ParseException         The response could not be parsed."])
        out += ["  @Override", f"  public {self.returns.java} execute() throws IOException, SpotifyWebApiException, ParseException {{",
                f"    return {self.returns.expression(call + '()')};", "  }", ""]
        out += doc(2, [f"   * Builder class for building a {{@link {self.cls}}}."],
                   ["   " + line[1:] for line in deprecation] if deprecation else None)
        out += ["  " + a for a in annotation]
        out += [f"  public static final class Builder extends {base} {{", ""]
        out += doc(4, [f"     * Create a new {{@link {self.cls}.Builder}} instance."],
                   ["     * @param accessToken Required. A valid access token from the Spotify Accounts service."])
        out += ["    public Builder(final String accessToken) {", "      super(accessToken);", "    }"]
        for p in self.params:
            out += [""] + self.setter(p, overrides)
        out += [""] + doc(4, ["     * The request build method."], [f"     * @return A {{@link {self.cls}}}."])
        out += ["    @Override", f"    public {self.cls} build() {{"]
        if has_body:
            out.append("      setContentType(ContentType.APPLICATION_JSON);")
        path = self.path
        for name, value in self.fixed.items():
            if "{" + name + "}" in path:
                path = path.replace("{" + name + "}", str(value))
            else:
                out.append(f'      setQueryParameter("{name}", "{value}");')
        out += [f'      setPath("/v1{path}");', f"      return new {self.cls}(this);", "    }", "",
                "    @Override", "    protected Builder self() {", "      return this;", "    }", "  }", "}", ""]
        return "\n".join(out)

    def api_method(self):
        lines = doc(2, wrap(summary(self.op), 2),
                    [line for p in self.required
                     for line in wrap(javadoc_text(p.description), 2, f"@param {p.method} ", " " * len(f"@param {p.method} "))]
                    + [f"   * @return A {{@link {self.cls}.Builder}}.",
                       f'   * @see <a href="{REFERENCE}{self.entry["operation"]}">Spotify Web API reference</a>'],
                    ["   * @deprecated This endpoint has been deprecated by Spotify."] if self.deprecated else None)
        if self.deprecated:
            lines.append("  @Deprecated")
        args = ", ".join(f"{p.java} {p.method}" for p in self.required)
        lines.append(f"  public {self.cls}.Builder {self.method}({args}) {{")
        lines.append(f"    return new {self.cls}.Builder(accessToken)")
        chain = ["      .setDefaults(httpManager, scheme, host, port)"] + [f"      .{p.method}({p.method})" for p in self.required]
        chain[-1] += ";"
        return lines + chain + ["  }"]


# --- SpotifyApi --------------------------------------------------------------------------------------

def splice(text, tag, body):
    start, end = f"// <{tag}>", f"// </{tag}>"
    pattern = re.compile(r"([ \t]*)" + re.escape(start) + r"\n.*?" + re.escape(end), re.S)
    m = pattern.search(text)
    if not m:
        raise SystemExit(f"SpotifyApi.java has no {start} ... {end} region")
    indent = m.group(1)
    return text[:m.start()] + indent + start + "\n" + body + indent + end + text[m.end():]


def render_api(requests):
    imports = set()
    for r in requests:
        imports.add(r.qualified)
        for p in r.required:
            imports |= {i for i in p.imports if not i.startswith(BASE + ".internal")}
    import_block = "".join(f"import {i};\n" for i in sorted(imports))
    methods = []
    for r in requests:
        methods += [""] + r.api_method()
    method_block = "\n".join(methods[1:]) + "\n"
    text = API.read_text()
    text = splice(text, "generated-imports", import_block)
    text = splice(text, "generated-requests", method_block)
    return text


# --- main --------------------------------------------------------------------------------------------

def main():
    check = "--check" in sys.argv[1:]
    spec = Spec()
    descriptor = yaml.safe_load(DESCRIPTOR.read_text())
    files, requests, failures = {}, [], []
    for package, classes in descriptor.items():
        for cls, entry in classes.items():
            try:
                request = Request(spec, package, cls, entry)
                files[SOURCES / DATA.replace(".", "/") / package / (cls + ".java")] = request.render()
                requests.append(request)
            except Unsupported as e:
                failures.append(f"{package}/{cls}: {e}")
    if failures:
        sys.exit("cannot generate:\n  " + "\n  ".join(failures))
    files[API] = render_api(requests)

    stale = [path for path, text in files.items() if not path.exists() or path.read_text() != text]
    for path in stale:
        if not check:
            path.write_text(files[path])
        print(("out of date: " if check else "written: ") + str(path.relative_to(ROOT)))
    if check and stale:
        sys.exit("run ./codegen/generate.py and commit the result")


if __name__ == "__main__":
    main()
